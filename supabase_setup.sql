DROP POLICY IF EXISTS "Admins read order items" ON public.order_items;
CREATE POLICY "Admins read order items" ON public.order_items FOR SELECT TO authenticated USING (public.is_admin());

-- 4) Pedido público com preço calculado no banco, nunca confiando no preço enviado pelo navegador.
CREATE OR REPLACE FUNCTION public.create_order(
  p_customer_name TEXT,
  p_customer_phone TEXT,
  p_fulfillment TEXT,
  p_address TEXT,
  p_payment_method TEXT,
  p_notes TEXT,
  p_delivery_fee NUMERIC,
  p_items JSONB
) RETURNS UUID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_order_id UUID;
  v_item JSONB;
  v_product public.products%ROWTYPE;
  v_size TEXT;
  v_base NUMERIC(10,2);
  v_extras_total NUMERIC(10,2);
  v_extra JSONB;
  v_extra_name TEXT;
  v_extra_price NUMERIC(10,2);
  v_qty INTEGER;
  v_line_total NUMERIC(10,2);
  v_total NUMERIC(10,2) := 0;
  v_final_fee NUMERIC(10,2) := 0;
  v_extras_snapshot JSONB;
BEGIN
  IF length(trim(coalesce(p_customer_name,''))) < 2 THEN RAISE EXCEPTION 'Informe o nome do cliente.'; END IF;
  IF p_fulfillment NOT IN ('delivery','pickup') THEN RAISE EXCEPTION 'Tipo de entrega inválido.'; END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' THEN RAISE EXCEPTION 'Formato de pedido inválido.'; END IF;
  IF jsonb_array_length(p_items) = 0 THEN RAISE EXCEPTION 'O pedido está vazio.'; END IF;
  IF jsonb_array_length(p_items) > 50 THEN RAISE EXCEPTION 'Muitos itens no pedido.'; END IF;
  INSERT INTO public.orders(customer_name, customer_phone, fulfillment, address, payment_method, notes, delivery_fee, total)
  VALUES (trim(p_customer_name), coalesce(p_customer_phone,''), p_fulfillment, coalesce(p_address,''), coalesce(p_payment_method,'PIX'), coalesce(p_notes,''), 0, 0)
  RETURNING id INTO v_order_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    SELECT * INTO v_product FROM public.products WHERE id = (v_item->>'product_id')::BIGINT AND available = TRUE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Um produto não está mais disponível.'; END IF;
    v_qty := greatest(1, least(50, coalesce((v_item->>'quantity')::INTEGER,1)));
    v_size := coalesce(v_item->>'size','');
    IF v_product.prices IS NOT NULL AND v_product.prices ? v_size THEN
      v_base := (v_product.prices->>v_size)::NUMERIC;
    ELSE
      v_base := v_product.price;
    END IF;
    v_extras_total := 0;
    v_extras_snapshot := '[]'::jsonb;
    IF jsonb_typeof(coalesce(v_item->'extras','[]'::jsonb)) = 'array' THEN
      FOR v_extra IN SELECT value FROM jsonb_array_elements(coalesce(v_item->'extras','[]'::jsonb)) LOOP
        v_extra_name := CASE v_extra->>'id' WHEN 'catupiry' THEN 'Catupiry' WHEN 'bacon' THEN 'Bacon' WHEN 'queijo' THEN 'Extra queijo' ELSE NULL END;
        v_extra_price := CASE v_extra->>'id' WHEN 'catupiry' THEN 5 WHEN 'bacon' THEN 6 WHEN 'queijo' THEN 5 ELSE 0 END;
        IF v_extra_name IS NOT NULL THEN
          v_extras_total := v_extras_total + v_extra_price;
          v_extras_snapshot := v_extras_snapshot || jsonb_build_array(jsonb_build_object('id',v_extra->>'id','name',v_extra_name,'price',v_extra_price));
        END IF;
      END LOOP;
    END IF;
    v_line_total := (v_base + v_extras_total) * v_qty;
    v_total := v_total + v_line_total;
    INSERT INTO public.order_items(order_id, product_id, product_name, size, unit_price, quantity, extras, note)
    VALUES (v_order_id, v_product.id, v_product.name, v_size, v_base + v_extras_total, v_qty, v_extras_snapshot, coalesce(v_item->>'note',''));
  END LOOP;
  -- Taxa calculada no banco para evitar que o navegador manipule os indicadores.
  v_final_fee := CASE WHEN p_fulfillment = 'pickup' OR v_total >= 80 THEN 0 ELSE 5 END;
  UPDATE public.orders SET delivery_fee = v_final_fee, total = v_total + v_final_fee WHERE id = v_order_id;
  RETURN v_order_id;
END;
$$;
REVOKE ALL ON FUNCTION public.create_order(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,NUMERIC,JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_order(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,NUMERIC,JSONB) TO anon, authenticated;

